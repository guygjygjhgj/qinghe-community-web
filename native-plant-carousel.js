import {myPlants} from './domain.js';

export function nativePlantCards(state){
 const plants=myPlants(state);
 return plants.length?plants:[{id:'reference-mint',name:'薄荷盆栽',location:'阳台',reference:true}];
}

export function prepareNativePlantCarousel(root){
 const card=root.querySelector('[data-name="plant／原图定位分层"]');
 if(!card||card.querySelector('[data-native-plant-motion]'))return;
 // Keep the original artboard coordinate origin for every image and calendar slot.
 const motion=document.createElement('div');
 motion.dataset.nativePlantMotion='true';motion.className='native-plant-motion';
 Object.assign(motion.style,{position:'absolute',left:'0',top:'0',width:'750px',height:root.style.height,pointerEvents:'none',touchAction:'pan-y pinch-zoom',transform:'translateX(0px)'});
 while(card.firstChild)motion.append(card.firstChild);
 card.append(motion);card.setAttribute('aria-label','我的植物卡片，可左右滑动');
}

// A replacement canvas must also swallow the click generated by the completed drag.
const clickGuards=new WeakMap();
export function bindNativePlantCarousel({root,count,index=0,onSelect,entry=0,window:win=root?.ownerDocument.defaultView}){
 const motion=root?.querySelector('[data-native-plant-motion]');
 if(!motion)return null;
 const doc=root.ownerDocument,guard=clickGuards.get(doc)||{until:0};clickGuards.set(doc,guard);
 let disposed=false,locked=false,drag=null,offset=0,animation=null,wheel=0;
 const inside=target=>target?.closest?.('[data-name="plant／原图定位分层"],[data-name="plant-side／原图定位分层"]');
 const editable=target=>target?.closest?.('input,textarea,select,button');
 const scale=()=>Math.max(.01,root.getBoundingClientRect().width/750||1);
 const move=x=>{offset=x;motion.style.transform='translateX('+x+'px)';};
 const tween=(from,to,done=()=>{})=>{
  animation?.cancel();move(to);
  if(!motion.animate||win.matchMedia?.('(prefers-reduced-motion: reduce)').matches){done();return;}
  animation=motion.animate([{transform:'translateX('+from+'px)'},{transform:'translateX('+to+'px)'}],{duration:160,easing:'cubic-bezier(.2,.7,.2,1)'});
  animation.finished.then(()=>{if(!disposed)done();},()=>{});
 };
 const step=delta=>{
  if(disposed||locked)return;
  const direction=delta<0?-1:1;
  if(count<2){locked=true;tween(offset,0,()=>{locked=false;});return;}
  locked=true;
  tween(offset,-direction*750,()=>onSelect((index+direction+count)%count,direction));
 };
 const down=e=>{
  if(locked||!inside(e.target)||editable(e.target)||e.isPrimary===false||e.button>0)return;
  drag={id:e.pointerId,x:e.clientX,y:e.clientY,axis:null};
 };
 const movePointer=e=>{
  if(!drag||drag.id!==e.pointerId||drag.axis==='vertical')return;
  const dx=e.clientX-drag.x,dy=e.clientY-drag.y;
  if(!drag.axis){if(Math.max(Math.abs(dx),Math.abs(dy))<8)return;
   if(Math.abs(dy)>Math.abs(dx)){drag.axis='vertical';return;}
   drag.axis='horizontal';root.dataset.plantDragging='true';
   try{root.setPointerCapture?.(e.pointerId);}catch{}
  }
  e.preventDefault();move(dx/scale()*(count<2?.25:1));
 };
 const finish=(e,cancel=false)=>{
  if(!drag||(e&&drag.id!==e.pointerId))return;
  const horizontal=drag.axis==='horizontal',id=drag.id;drag=null;delete root.dataset.plantDragging;
  try{if(root.hasPointerCapture?.(id))root.releasePointerCapture(id);}catch{}
  if(!horizontal)return;
  guard.until=Date.now()+500;
  if(!cancel&&count>1&&Math.abs(offset)>=90)step(offset<0?1:-1);
  else{locked=true;tween(offset,0,()=>{locked=false;});}
 };
 const up=e=>finish(e),cancel=e=>finish(e,true),blur=()=>finish(null,true);
 // Touch begins with implicit capture on the photo; transferring it to the canvas
 // emits a bubbling lostpointercapture from that child, not a cancelled gesture.
 const lost=e=>{if(e.target===root)finish(e,true);};
 const click=e=>{if(inside(e.target)&&Date.now()<guard.until){e.preventDefault();e.stopImmediatePropagation();}};
 const key=e=>{if(inside(e.target)&&!editable(e.target)&&['ArrowLeft','ArrowRight'].includes(e.key)){e.preventDefault();step(e.key==='ArrowLeft'?-1:1);}};
 const scroll=e=>{
  if(!inside(e.target)||editable(e.target)||Math.abs(e.deltaX)<=Math.abs(e.deltaY))return;
  e.preventDefault();
  const continuing=Date.now()-(guard.wheelAt||0)<250;guard.wheelAt=Date.now();
  if(!continuing){wheel=0;guard.wheelLocked=false;}
  if(locked||guard.wheelLocked)return;
  wheel+=e.deltaX*(e.deltaMode===1?16:e.deltaMode===2?root.clientWidth:1);
  if(Math.abs(wheel)>=50){guard.wheelLocked=true;step(wheel<0?-1:1);wheel=0;}
 };
 const dragImage=e=>{if(inside(e.target))e.preventDefault();};
 const listeners=[['pointerdown',down],['pointermove',movePointer,{passive:false}],['pointerup',up],['pointercancel',cancel],['lostpointercapture',lost],['click',click,true],['keydown',key],['wheel',scroll,{passive:false}],['dragstart',dragImage]];
 for(const args of listeners)root.addEventListener(...args);win.addEventListener('blur',blur);
 if(entry){locked=true;tween(entry*750,0,()=>{locked=false;});}
 return {step,dispose(){disposed=true;animation?.cancel();for(const args of listeners)root.removeEventListener(...args);win.removeEventListener('blur',blur);delete root.dataset.plantDragging;}};
}
